"""Era conformance audit, mob ability layer.

For every creature present in both cMaNGOS classic and the realm world DB,
compares the SET of spells the creature casts:
  era  : creature_spell_list (via creature_template.SpellList) + creature_ai_scripts cast actions
  realm: smart_scripts (cast actions, incl. actionlists) + creature_template_spell
Realm spell ids are normalised (clone 3xxxxx / 4xxxxx -> base id).
Rows: creature_id,name,spell_id,spell_name,status  (status = missing_in_realm | extra_in_realm)
Only checks WHICH spells are cast; timers/cooldowns are a later layer. Creatures driven by
a C++ ScriptName are flagged "cpp" because their casts are invisible to this check.

  python -I tools/audit/mob_audit.py --classic-db era-data/classicmangos.sqlite \
      --mysql-socket /tmp/scratch-db/sock [--out audit-mobs.csv]
"""
import argparse, csv, sqlite3, subprocess
from collections import defaultdict
from pathlib import Path

def my(sock, sql):
    r = subprocess.run(["mariadb", "--no-defaults", "-S", sock, "-uroot", "acore_world", "-B", "-N", "-e", sql],
                       capture_output=True, text=True, check=True)
    return [l.split("\t") for l in r.stdout.splitlines()]

def norm(s):
    s = int(s)
    return s % 100000 if s >= 300000 else s

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--classic-db", required=True, type=Path)
    ap.add_argument("--mysql-socket", required=True)
    ap.add_argument("--out", type=Path, default=Path("audit-mobs.csv"))
    ap.add_argument("--emit-fix", type=Path, help="write SQL repointing wrong_version casts at the era spell's "
                    "Vanilla copy (id+300000); also writes <fix>.spells with the era ids needing a copy")
    a = ap.parse_args()
    db = sqlite3.connect(f"file:{a.classic_db}?mode=ro", uri=True)
    sname = {r[0]: r[1] for r in db.execute("select Id, SpellName from spell_template")}
    era = defaultdict(set)
    for cid, sid in db.execute("""select t.Entry, l.SpellId from creature_template t
            join creature_spell_list l on l.Id = t.SpellList where t.SpellList>0 and l.SpellId>0"""):
        era[cid].add(sid)
    for row in db.execute("select creature_id, action1_type,action1_param1,action2_type,action2_param1,"
                          "action3_type,action3_param1 from creature_ai_scripts"):
        for t, p in zip(row[1::2], row[2::2]):
            if t == 11 and p:
                era[row[0]].add(p)
    names = {r[0]: r[1] for r in db.execute("select Entry, Name from creature_template")}

    realm = defaultdict(set)
    for ent, sid in my(a.mysql_socket, "select entryorguid, action_param1 from smart_scripts "
                       "where source_type=0 and action_type in (11,85) and entryorguid>0"):
        realm[int(ent)].add(norm(sid))
    # actionlists: timed lists triggered by action 80; entryorguid = creature*100+n
    for ent, sid in my(a.mysql_socket, "select floor(entryorguid/100), action_param1 from smart_scripts "
                       "where source_type=9 and action_type in (11,85)"):
        realm[int(ent)].add(norm(sid))
    for ent, sid in my(a.mysql_socket, "select CreatureID, Spell from creature_template_spell"):
        realm[int(ent)].add(norm(sid))
    cpp = {int(r[0]) for r in my(a.mysql_socket, "select entry from creature_template where ScriptName<>''")}
    have = {int(r[0]) for r in my(a.mysql_socket, "select entry from creature_template")}

    rows, n_cpp = [], 0
    for cid in sorted(set(era) & have):
        miss, extra = era[cid] - realm[cid], realm[cid] - era[cid]
        # same spell name but different id/rank: the realm runs a different version
        for m in sorted(miss):
            twins = [x for x in extra if sname.get(x) and sname.get(x) == sname.get(m)]
            if twins:
                rows.append((cid, names.get(cid), m, sname.get(m), f"wrong_version(realm uses {','.join(map(str, twins))})",
                             "cpp" if cid in cpp else ""))
                miss.discard(m)
                extra -= set(twins)
        tag = "cpp" if cid in cpp else ""
        if not (miss or extra):
            continue
        for s in sorted(miss):
            rows.append((cid, names.get(cid), s, sname.get(s), "missing_in_realm", tag))
        for s in sorted(extra):
            rows.append((cid, names.get(cid), s, sname.get(s), "extra_in_realm", tag))
    if a.emit_fix:
        sql, need = ["-- Generated by tools/audit/mob_audit.py --emit-fix: casts that use another version of the",
                     "-- same-named spell now use the Vanilla (1.12.1) spell. Do not edit by hand."], set()
        for cid, nm, era_id, sn, st, _ in rows:
            if not st.startswith("wrong_version"):
                continue
            for twin in st[st.index("uses ") + 5:-1].split(","):
                need.add(era_id)
                new = era_id + 300000
                sql.append(f"UPDATE `smart_scripts` SET `action_param1`={new} WHERE `source_type`=0 AND "
                           f"`entryorguid`={cid} AND `action_type` IN (11,85) AND `action_param1` IN ({twin},{int(twin)+300000});"
                           f" -- {nm}: {sn}")
                sql.append(f"UPDATE `creature_template_spell` SET `Spell`={new} WHERE `CreatureID`={cid} AND `Spell`={twin};")
        a.emit_fix.write_text("\n".join(sql) + "\n")
        Path(str(a.emit_fix) + ".spells").write_text("\n".join(map(str, sorted(need))) + "\n")
        print("fix SQL:", a.emit_fix, "| era spells needing a copy:", len(need))
    with open(a.out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["creature_id", "name", "spell_id", "spell_name", "status", "cpp_script"])
        w.writerows(rows)
    c = {x[0] for x in rows}
    print("wrong_version rows:", sum(r[4].startswith("wrong_version") for r in rows))
    print("creatures compared:", len(set(era) & have), " with a spell-set diff:", len(c),
          " missing rows:", sum(r[4] == "missing_in_realm" for r in rows),
          " extra rows:", sum(r[4] == "extra_in_realm" for r in rows), "->", a.out)

main()
